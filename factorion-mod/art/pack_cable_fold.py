"""Pack Blender Cable fold layers at Factorio's 64 px/tile (scale .5).

uv run --no-sync python pack_cable_fold.py RENDER_DIR SPRITE_DIR

The Blender metadata is the source of truth for every layer's anchor,
ports, circuit studs and light position. No guessed offsets or orientation
specific image stretching. Six glow frames share one crop and one atlas.
"""

import argparse
import json
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("render_dir", type=Path)
    parser.add_argument("sprite_dir", type=Path)
    parser.add_argument("--icon-out", type=Path)
    args = parser.parse_args()
    meta = json.loads((args.render_dir / "render.json").read_text())
    orientation = meta["orientation"]
    ratio = 64 / meta["pixels_per_tile"]
    anchor = [n * ratio for n in meta["anchor"]]
    args.sprite_dir.mkdir(parents=True, exist_ok=True)

    def load(name):
        image = Image.open(args.render_dir / (name + ".png")).convert("RGBA")
        return image.resize(
            tuple(round(v * ratio) for v in image.size), Image.Resampling.LANCZOS
        )

    def bounds(images):
        alpha = images[0].getchannel("A")
        for image in images[1:]:
            alpha = ImageChops.lighter(alpha, image.getchannel("A"))
        box = alpha.point(lambda a: 255 if a > 2 else 0).getbbox()
        if not box:
            raise ValueError("Empty rendered layer")
        left, top, right, bottom = box
        left, top, right, bottom = left - 2, top - 2, right + 2, bottom + 2
        right += (right - left) % 2
        bottom += (bottom - top) % 2
        return left, top, right, bottom

    parts = {}
    prefix = "gpu-server-" + orientation
    main_image = load("main")
    # Small sharpening only; preserve the true anti-aliased alpha silhouette.
    alpha = main_image.getchannel("A")
    main_image = main_image.filter(
        ImageFilter.UnsharpMask(radius=0.65, percent=45, threshold=3)
    )
    main_image.putalpha(alpha)
    shadow = load("shadow")
    shadow_alpha = shadow.getchannel("A").filter(ImageFilter.GaussianBlur(0.45))
    shadow = Image.new("RGBA", shadow.size, (0, 0, 0, 0))
    shadow.putalpha(shadow_alpha)
    glows = [load("glow-" + str(i)) for i in range(6)]
    for part, images in [("main", [main_image]), ("shadow", [shadow]), ("glow", glows)]:
        left, top, right, bottom = bounds(images)
        width, height = right - left, bottom - top
        cropped = [image.crop((left, top, right, bottom)) for image in images]
        atlas = Image.new("RGBA", (width * len(images), height))
        for index, image in enumerate(cropped):
            atlas.paste(image, (index * width, 0))
        name = prefix + ("" if part == "main" else "-" + part) + ".png"
        atlas.save(args.sprite_dir / name)
        parts[part] = {
            "filename": "__factorion__/graphics/entity/" + name,
            "width": width,
            "height": height,
            "shift": [
                ((left + right) / 2 - anchor[0]) / 64,
                ((top + bottom) / 2 - anchor[1]) / 64,
            ],
        }
        if part == "glow":
            parts[part]["frame_count"] = len(images)
    parts["footprint"] = meta["footprint"]
    parts["geometry_sha256"] = meta["geometry_sha256"]
    parts["assembly_rotation_degrees"] = meta["assembly_rotation_degrees"]
    parts["data_port"] = meta["markers"]["data_port"]
    parts["activity_light"] = meta["markers"]["activity_light"]
    parts["circuit"] = {
        "wire": {c: meta["markers"][c] for c in ("red", "green")},
        "shadow": meta["wire_shadow"],
    }

    def lua(value):
        if isinstance(value, dict):
            return "{ " + ", ".join(k + " = " + lua(v) for k, v in value.items()) + " }"
        if isinstance(value, list):
            return "{ " + ", ".join(lua(v) for v in value) + " }"
        if isinstance(value, str):
            return json.dumps(value)
        return (
            format(value, ".6f").rstrip("0").rstrip(".")
            if isinstance(value, float)
            else str(value)
        )

    (args.sprite_dir / (prefix + ".lua")).write_text(
        "-- Generated by art/pack_cable_fold.py\nreturn " + lua(parts) + "\n"
    )
    (args.sprite_dir / (prefix + ".json")).write_text(
        json.dumps(parts, indent=2) + "\n"
    )
    print(
        orientation,
        {
            part: (data["width"], data["height"])
            for part, data in parts.items()
            if isinstance(data, dict) and "width" in data
        },
    )

    if orientation == "horizontal" and args.icon_out:
        icon_path = args.render_dir / "icon.png"
        if icon_path.exists():
            icon = Image.open(icon_path).convert("RGBA")
            icon = icon.crop(icon.getchannel("A").getbbox())
            icon.thumbnail((60, 60), Image.Resampling.LANCZOS)
            canvas = Image.new("RGBA", (64, 64))
            canvas.alpha_composite(
                icon, ((64 - icon.width) // 2, (64 - icon.height) // 2)
            )
            args.icon_out.parent.mkdir(parents=True, exist_ok=True)
            canvas.save(args.icon_out)


if __name__ == "__main__":
    main()
